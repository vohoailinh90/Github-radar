#!/usr/bin/env python3
"""Keep radar's vendored copy of the impeccable design skill honest.

  vendor_impeccable.py snapshot <impeccable checkout>   copy the skill, its agents and its license in; rewrite the lock
  vendor_impeccable.py check                            exit 1 when a vendored file differs from the lock

The copy is for reuse: the skill is installed into other repositories for UI design work (docs/impeccable.md).
It stays byte-for-byte what upstream builds, so a change is a re-sync, never a hand edit. The lock
(.claude/skills/impeccable.lock.json) records the upstream commit and a sha256 per file; `check` is also a test.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
LOCK = Path(".claude") / "skills" / "impeccable.lock.json"
SKILL = Path(".claude") / "skills" / "impeccable"
AGENTS = Path(".claude") / "agents"
THIRD_PARTY = Path("docs") / "third-party" / "impeccable"
UPSTREAM = "https://github.com/pbakaus/impeccable"
LICENSE_ID = "Apache-2.0"
# Only POSIX file modes carry an executable bit; Windows reports none for scripts/impeccable (it runs impeccable.cmd there).
POSIX = os.name == "posix"


def vendored_files(root: Path) -> list[str]:
    """Every file this vendoring owns under `root`, as sorted repo-relative POSIX paths."""
    found = [p for p in (root / SKILL).rglob("*") if p.is_file()]
    found += sorted((root / AGENTS).glob("impeccable-*.md"))
    found += [p for p in (root / THIRD_PARTY).rglob("*") if p.is_file()] if (root / THIRD_PARTY).is_dir() else []
    return sorted(p.relative_to(root).as_posix() for p in found)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def is_executable(path: Path) -> bool:
    return bool(path.stat().st_mode & 0o111)


def problems(root: Path = HERE) -> list[str]:
    """Differences between the vendored tree under `root` and its lock; empty means in sync."""
    lock_path = root / LOCK
    if not lock_path.is_file():
        return [f"missing {LOCK.as_posix()}"]
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    locked = lock["files"]
    here = vendored_files(root) if (root / SKILL).is_dir() else []
    out = [f"missing {p}" for p in sorted(set(locked) - set(here))]
    out += [f"not in the lock: {p}" for p in sorted(set(here) - set(locked))]
    for p in sorted(set(here) & set(locked)):
        if sha256(root / p) != locked[p]:
            out.append(f"changed {p}")
    for p in lock["executable"] if POSIX else []:
        if (root / p).is_file() and not is_executable(root / p):
            out.append(f"not executable {p}")
    return out


def skill_version(skill: Path) -> str:
    match = re.search(r"^version:\s*(\S+)\s*$", (skill / "SKILL.md").read_text(encoding="utf-8"), re.M)
    if not match:
        raise SystemExit("snapshot: SKILL.md has no `version:` line")
    return match.group(1)


def snapshot(upstream: Path, root: Path = HERE) -> None:
    if not POSIX:
        raise SystemExit("snapshot: run it on Linux, macOS or WSL; this platform cannot record the launcher's executable bit")
    git = ["git", "-C", str(upstream)]
    if subprocess.run(git + ["status", "--porcelain"], capture_output=True, text=True, check=True).stdout.strip():
        raise SystemExit("snapshot: the checkout has uncommitted changes, so no commit describes it")
    commit = subprocess.run(git + ["rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    src_skill = upstream / SKILL
    agents = sorted((upstream / AGENTS).glob("impeccable-*.md"))
    needed = [src_skill / "SKILL.md", src_skill / "scripts" / "VERSION", upstream / "LICENSE", upstream / "NOTICE.md"]
    absent = [p.relative_to(upstream).as_posix() for p in needed if not p.is_file()]
    if absent or not agents:
        raise SystemExit(f"snapshot: not the impeccable repository, or its layout changed; missing {absent or 'agents'}")
    version = skill_version(src_skill)        # everything is verified before anything is deleted
    shutil.rmtree(root / SKILL, ignore_errors=True)
    shutil.copytree(src_skill, root / SKILL, symlinks=False)
    (root / AGENTS).mkdir(parents=True, exist_ok=True)
    for old in (root / AGENTS).glob("impeccable-*.md"):
        old.unlink()
    for agent in agents:
        shutil.copy2(agent, root / AGENTS / agent.name)
    shutil.rmtree(root / THIRD_PARTY, ignore_errors=True)
    (root / THIRD_PARTY).mkdir(parents=True)
    for name in ("LICENSE", "NOTICE.md"):
        shutil.copy2(upstream / name, root / THIRD_PARTY / name)
    files = vendored_files(root)
    lock = {
        "_source": "generated by scripts/vendor_impeccable.py snapshot; do not edit by hand",
        "upstream": UPSTREAM, "commit": commit, "license": LICENSE_ID,
        "skill_version": version,
        "engine_version": (root / SKILL / "scripts" / "VERSION").read_text(encoding="utf-8").strip(),
        "executable": [p for p in files if is_executable(root / p)],
        "files": {p: sha256(root / p) for p in files},
    }
    (root / LOCK).write_text(json.dumps(lock, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"vendored {len(files)} files from {UPSTREAM}@{commit[:12]} (skill {lock['skill_version']})")


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[1] == "snapshot":
        snapshot(Path(argv[2]).resolve())
        return 0
    if len(argv) == 2 and argv[1] == "check":
        found = problems()
        for line in found:
            print(f"vendor_impeccable: {line}")
        print(f"vendor_impeccable: {len(found)} problem(s)")
        return 1 if found else 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    os.chdir(HERE)
    sys.exit(main(sys.argv))
