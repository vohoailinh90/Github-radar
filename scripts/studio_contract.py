#!/usr/bin/env python3
"""Keep radar's copy of the studio contract honest.

  studio_contract.py snapshot <studio checkout>          rewrite contracts/studio-layouts.json
  studio_contract.py diff     <studio checkout>          exit 1 when the snapshot has drifted
  studio_contract.py verify   <studio checkout> <bundle> run the REAL `studio.py check` on a bundle
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SNAPSHOT = HERE / "contracts" / "studio-layouts.json"


def read_studio(studio: Path) -> dict:
    sys.path.insert(0, str(studio))
    try:
        from mkt import check, i18n, model, page, platforms  # type: ignore
        from mkt.layouts import ENUMS, FIELDS, LAYOUTS  # type: ignore
    finally:
        sys.path.pop(0)
    return {
        "_source": "generated by scripts/studio_contract.py snapshot; do not edit by hand",
        "langs": list(i18n.LANGS), "platforms": {k: {"required": list(v["required"]), **(
            {"caption_limit": v["caption_limit"]} if "caption_limit" in v else {})} for k, v in platforms.PLATFORMS.items()},
        "layouts": {n: {"required": list(LAYOUTS[n][1]), "fields": list(FIELDS[n])} for n in sorted(LAYOUTS)},
        "enums": {k: list(v) for k, v in ENUMS.items()},
        "post_keys": list(check.POST_KEYS), "post_statuses": list(model.POST_STATUSES),
        "tool_statuses": list(model.TOOL_STATUSES), "formats": list(page.FORMATS),
        "max_slides": check.MAX_SLIDES, "hook_limit": check.HOOK_LIMIT,
    }


def main(argv: list[str]) -> int:
    if len(argv) < 3 or argv[1] not in ("snapshot", "diff", "verify"):
        print(__doc__)
        return 2
    studio = Path(argv[2]).resolve()
    if argv[1] in ("snapshot", "diff"):
        current = read_studio(studio)
        if argv[1] == "snapshot":
            SNAPSHOT.write_text(json.dumps(current, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            print(f"wrote {SNAPSHOT.relative_to(HERE)}")
            return 0
        if json.loads(SNAPSHOT.read_text(encoding="utf-8")) != current:
            print("contracts/studio-layouts.json has drifted from the studio: run `snapshot`")
            return 1
        print("studio contract snapshot is current")
        return 0
    bundle = Path(argv[3]).resolve()
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "studio"
        work.mkdir()
        for name in ("studio.py", "studio.yaml", "mkt"):
            src = studio / name
            if src.is_dir():
                shutil.copytree(src, work / name, ignore=shutil.ignore_patterns("__pycache__"))
            elif src.exists():
                shutil.copy(src, work / name)
        shutil.copytree(bundle, work, dirs_exist_ok=True)
        slugs = sorted(p.name for p in (work / "campaigns").iterdir() if p.is_dir())
        status = 0
        for slug in slugs:
            proc = subprocess.run([sys.executable, "studio.py", "check", slug], cwd=work, text=True,
                                  capture_output=True)
            print(proc.stdout + proc.stderr, end="")
            status = status or proc.returncode
        return status


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
